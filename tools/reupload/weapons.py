import sys,os; sys.path.insert(0,os.path.dirname(os.path.abspath(__file__))); import rbx
def mul(a,b):
    ax,ay,az=a[:3]; A=a[3:]; bx,by,bz=b[:3]; B=b[3:]
    R=[sum(A[i*3+k]*B[k*3+j] for k in range(3)) for i in range(3) for j in range(3)]
    p=[ax+A[0]*bx+A[1]*by+A[2]*bz, ay+A[3]*bx+A[4]*by+A[5]*bz, az+A[6]*bx+A[7]*by+A[8]*bz]
    return tuple(p+R)
def inv(a):
    A=a[3:]; T=[A[0],A[3],A[6],A[1],A[4],A[7],A[2],A[5],A[8]]; x,y,z=a[:3]
    return tuple([-(T[0]*x+T[1]*y+T[2]*z),-(T[3]*x+T[4]*y+T[5]*z),-(T[6]*x+T[7]*y+T[8]*z)]+T)
def n(v): return repr(round(float(v),4))
I=rbx.load(sys.argv[1])
# (key, vania folder, model). The first three are each class's default; the rest are variants that gear items name.
PICK=[("Warden","Sword","Mika"),("Assassin","Dagger","Long Dagger"),("Cleric","GreatHammer","OGreat Hammer"),
    ("Sword","Sword","Sword"),("Sabre","Sword","Sabre"),("Cutlass","Sword","Cutlass"),("Rusted Sword","Sword","Rusted Sword"),
    ("Curved Dagger","Dagger","Curved Dagger"),("Rusted Dagger","Dagger","Rusted Dagger"),
    ("Great Hammer","GreatHammer","Great Hammer"),("Rusted Hammer","GreatHammer","Rusted GreatHammer")]
out=["-- Generated by tools/reupload/weapons.py from the vania place's weapon models. Do not edit by hand.",
"-- Keyed by class (its default weapon) or by variant name (an Items weapon's `model`). `grip` is the C0 of the",
"-- weld from the weapon's main part to the Hilt (vania's rig: a Hilt part",
"-- joined to the Right Arm, which the combat animations move). Each part's `cframe` is relative to the main part.",
"-- Materials are Enum.Material values, colours are 0-255. Meshes load in any game.","","return {"]
for cls,fold,name in PICK:
    W=[i for i in I.values() if i.path().endswith('ReplicatedStorage.Assets.AllModels.'+fold+'.'+name)][0]
    weld=[d for d in W.children if d.cls=='Motor6D' and d.name()=='Weld'][0]
    parts=[W]+[d for d in W.descendants() if d.cls=='MeshPart']
    sa=[d.cls for d in W.descendants() if d.cls=='SurfaceAppearance']
    out.append(f"\t[{cls!r}] = {{ -- {name}".replace("'", '"') + (" (has SurfaceAppearance, not copied)" if sa else ""))
    out.append("\t\tgrip = { "+", ".join(n(v) for v in weld.props['C0'])+" },")
    out.append("\t\tparts = {")
    winv=inv(W.props['CFrame'])
    for p in parts:
        pr=p.props; rel=mul(winv,pr['CFrame'])
        col=pr.get('Color3uint8',(163,162,165))
        out.append("\t\t\t{")
        out.append(f'\t\t\t\tmeshId = "{pr.get("MeshId",b"").decode()}",')
        if pr.get('TextureID'): out.append(f'\t\t\t\ttextureId = "{pr["TextureID"].decode()}",')
        out.append("\t\t\t\tsize = { "+", ".join(n(v) for v in pr['size'])+" },")
        out.append("\t\t\t\tcframe = { "+", ".join(n(v) for v in rel)+" },")
        out.append(f"\t\t\t\tcolor = {{ {col[0]}, {col[1]}, {col[2]} }},")
        out.append(f"\t\t\t\tmaterial = {pr.get('Material',256)},")
        if pr.get('Transparency'): out.append(f"\t\t\t\ttransparency = {n(pr['Transparency'])},")
        if pr.get('Reflectance'): out.append(f"\t\t\t\treflectance = {n(pr['Reflectance'])},")
        out.append("\t\t\t},")
    out.append("\t\t},\n\t},")
    print(cls,name,len(parts),'parts','SA' if sa else '')
out.append("}")
open(sys.argv[2],'w').write("\n".join(out)+"\n")
