"""Turn ParticleEmitter groups from a place file into a Luau data module (src/shared/VfxLibrary.luau).

Usage: python3 tools/reupload/vfx.py picks.json out.luau
picks.json: [{"key": "slash", "file": "place.rbxl", "root": "ServerStorage.Assets.X", "exclude": ["OLD"], "source": "vania"}]

Textures stay as the source's image IDs; images are public, so they load in any game.
"""
import json, os, struct, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import rbx

NUMBER = ["Brightness", "Drag", "LightEmission", "LightInfluence", "Rate", "ShapePartial", "TimeScale",
          "VelocityInheritance", "ZOffset"]
BOOL = ["LockedToPart", "FlipbookStartRandom", "WindAffectsDrag"]
RANGE = ["Lifetime", "Speed", "RotSpeed", "Rotation", "FlipbookFramerate"]
SEQUENCE = ["Size", "Transparency", "Squash"]
ENUMS = {"EmissionDirection": "NormalId", "Orientation": "ParticleOrientation", "Shape": "ParticleEmitterShape",
         "ShapeInOut": "ParticleEmitterShapeInOut", "ShapeStyle": "ParticleEmitterShapeStyle",
         "FlipbookLayout": "ParticleFlipbookLayout", "FlipbookMode": "ParticleFlipbookMode"}

def attributes(raw):
    out = {}
    if not raw or len(raw) < 4:
        return out
    n = struct.unpack_from("<I", raw, 0)[0]
    p = 4
    for _ in range(n):
        k, p = rbx._string(raw, p)
        t = raw[p]; p += 1
        if t == 0x06:
            out[k.decode()] = struct.unpack_from("<d", raw, p)[0]; p += 8
        elif t == 0x05:
            out[k.decode()] = struct.unpack_from("<f", raw, p)[0]; p += 4
        elif t == 0x03:
            out[k.decode()] = bool(raw[p]); p += 1
        elif t == 0x02:
            s, p = rbx._string(raw, p); out[k.decode()] = s.decode("utf-8", "replace")
        else:
            break
    return out

def num(v):
    return repr(round(float(v), 4))

def emitter_lua(e, indent):
    p = e.props
    tex = p.get("Texture", b"").decode("utf-8", "replace")
    attrs = attributes(p.get("AttributesSerialize", b""))
    count = int(attrs.get("EmitCount") or max(1, min(20, round((p.get("Rate") or 0) * 0.3))))
    fields = [f'Texture = "{tex}"', f"emitCount = {count}"]
    if attrs.get("EmitDelay"):
        fields.append(f"emitDelay = {num(attrs['EmitDelay'])}")
    for k in NUMBER:
        if k in p:
            fields.append(f"{k} = {num(p[k])}")
    for k in BOOL:
        if k in p:
            fields.append(f"{k} = {'true' if p[k] else 'false'}")
    for k in RANGE:
        if k in p:
            fields.append(f"{k} = {{ {num(p[k][0])}, {num(p[k][1])} }}")
    for k in SEQUENCE:
        if k in p:
            fields.append(f"{k} = {{ " + ", ".join(f"{{ {num(a)}, {num(b)}, {num(c)} }}" for a, b, c in p[k]) + " }")
    if "Color" in p:
        fields.append("Color = { " + ", ".join(f"{{ {num(t)}, {num(r)}, {num(g)}, {num(b)} }}" for t, r, g, b, _ in p["Color"]) + " }")
    if "Acceleration" in p:
        fields.append("Acceleration = { " + ", ".join(num(v) for v in p["Acceleration"]) + " }")
    if "SpreadAngle" in p:
        fields.append("SpreadAngle = { " + ", ".join(num(v) for v in p["SpreadAngle"]) + " }")
    for k, enum in ENUMS.items():
        if k in p:
            fields.append(f"{k} = {p[k]}")
    pad = "\t" * indent
    return pad + "{\n" + "".join(f"{pad}\t{f},\n" for f in fields) + pad + "},"

def main(picks_path, out_path):
    picks = json.load(open(picks_path))
    cache = {}
    blocks = []
    for pick in picks:
        if pick["file"] not in cache:
            cache[pick["file"]] = rbx.load(pick["file"])
        insts = cache[pick["file"]]
        root = pick["root"]
        groups = {}
        for i in insts.values():
            if i.cls != "ParticleEmitter":
                continue
            path = i.path()
            if not path.startswith(root + ".") or any(x in path[len(root):] for x in pick.get("exclude", [])):
                continue
            parent = i.parent
            cf = parent.props.get("CFrame") if parent is not None and parent.cls == "Attachment" else None
            key = parent.ref if cf else -1
            groups.setdefault(key, {"cf": cf, "emitters": []})["emitters"].append(i)
        lines = [f"\t-- {pick.get('source', '')}: {root}", f"\t{pick['key']} = {{"]
        for g in groups.values():
            cf = g["cf"]
            if cf:
                lines.append("\t\t{\n\t\t\tcframe = { " + ", ".join(num(v) for v in cf) + " },")
            else:
                lines.append("\t\t{")
            lines.append("\t\t\temitters = {")
            for e in g["emitters"]:
                lines.append(emitter_lua(e, 4))
            lines.append("\t\t\t},\n\t\t},")
        lines.append("\t},")
        blocks.append("\n".join(lines))
        print(pick["key"], sum(len(g["emitters"]) for g in groups.values()), "emitters in", len(groups), "groups")
    header = ("-- Generated by tools/reupload/vfx.py from particle effects in the vania and hxh places. Do not edit by hand.\n"
              "-- Each effect is a list of attachment groups; each group lists ParticleEmitter properties.\n"
              "-- Enum fields are stored as their Value numbers. cframe = attachment offset (x, y, z, then rotation).\n\n"
              "return {\n")
    open(out_path, "w").write(header + "\n".join(blocks) + "\n}\n")

if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
